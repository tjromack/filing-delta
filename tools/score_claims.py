"""Score the claim matcher against Trevor's blind labels (M5, FD-DEC 025 option B).

    python tools/score_claims.py --import <dir>   # once: labels from the page's db -> tests/golden/claims_labels.json
    python tools/score_claims.py                  # offline; writes docs/claims-eval.md

Per matcher outcome (and per reason for `not checked`): the share of sampled claims where the human label agrees,
with a Wilson 95% interval, plus the full confusion matrix. Corpus estimates scale each stratum's agreement by its
population. Refuses to run under any matcher version but the frozen one, or with unlabeled items.
"""
from __future__ import annotations

import json
import math
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from filing_delta.xbrl.claims_run import matcher_version  # noqa: E402

SAMPLE = ROOT / "tests" / "golden" / "claims_sample.json"
LABELS = ROOT / "tests" / "golden" / "claims_labels.json"
FROZEN = ROOT / "tests" / "golden" / "claims_matcher.json"
HUMAN = {"M": "matches", "N": "no matching tagged value", "G": "non-GAAP wording", "X": "not checked", "U": "unsure"}
ORDER = ["matches", "no matching tagged value", "non-GAAP wording", "not checked"]
# Items Claude explained to the labeler while labeling was under way: no longer blind, so not scored.
# C001: used on 2026-10-17 to explain what a "match" is (Apple FY2023 total net sales, $383.3 billion).
WORKED_EXAMPLES = {"C001"}


def wilson(k: int, n: int) -> tuple[float, float]:
    if n == 0:
        return float("nan"), float("nan")
    z, p = 1.96, k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return max(0.0, c - h), min(1.0, c + h)


def import_labels(src: Path) -> None:
    if LABELS.exists():
        raise SystemExit(f"{LABELS.name} exists; refusing to overwrite a committed record.")
    out = {}
    for f in sorted(src.rglob("*.json")):
        doc = json.loads(f.read_text(encoding="utf-8"))
        body = doc.get("data", doc)
        if re.fullmatch(r"C\d{3}", f.stem) and body.get("label") in HUMAN:
            out[f.stem] = {"label": body["label"], "code": body.get("code") or None, "note": body.get("note") or None,
                           "suggested": body.get("suggested"), "at": body.get("at")}
    LABELS.write_text(json.dumps(out, indent=1, sort_keys=True) + "\n", encoding="utf-8", newline="\n")
    print(f"imported {len(out)} labels -> {LABELS.relative_to(ROOT)}")


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    if "--import" in sys.argv:
        import_labels(Path(sys.argv[sys.argv.index("--import") + 1]))
        return
    frozen = json.loads(FROZEN.read_text(encoding="utf-8"))["matcher_version"]
    if matcher_version() != frozen:
        raise SystemExit(f"matcher {matcher_version()} != frozen {frozen}: scored only under the frozen rules.")
    sample = json.loads(SAMPLE.read_text(encoding="utf-8"))
    if not LABELS.exists():
        raise SystemExit("No labels yet: label the sample on the claim-check page, then run with --import <dir>.")
    labels = json.loads(LABELS.read_text(encoding="utf-8"))
    missing = [i["id"] for i in sample["items"] if i["id"] not in labels]
    if missing:
        raise SystemExit(f"{len(missing)} items unlabeled (e.g. {missing[:5]}).")
    pop = sample["population"]
    rows = [(i, HUMAN[labels[i["id"]]["label"]]) for i in sample["items"] if i["id"] not in WORKED_EXAMPLES]
    cm = Counter((i["matcher"]["outcome"], h) for i, h in rows)
    decided = [(i, h) for i, h in rows if h != "unsure"]
    overrides = [(i, h) for i, h in decided if h != i["matcher"]["outcome"]]
    lines = ["# Claim matcher evaluation (blind hand labels)", "",
             f"Matcher version `{frozen}` (frozen before sampling), 10-K Item 7 and 10-Q Part I Item 2 of the locked "
             f"corpus. {len(rows)} claims sampled from {sum(pop.values()):,}, stratified by the matcher's outcome and "
             "reason; labeled by Trevor **with the matcher's answer shown as a suggestion** (FD-DEC 026, "
             "`tests/golden/claims_labels.json`). Generated by `tools/score_claims.py`.", "",
             "`no matching tagged value` means an amount wasn't found among the filing's tagged values at its stated "
             "precision. It is not a finding that the statement is wrong.", "",
             "**These figures measure agreement with one human labeler, not accuracy.** The labels are one careful "
             "reader's judgment and can be wrong; every disagreement is listed below with its text so it can be "
             "checked. Labeling was **not blind**: the labeler saw the matcher's answer before answering, so agreement "
             "is biased upward by anchoring and is not an independent estimate of the matcher's precision. The most "
             "informative figure is the override count: where a reader looking at the evidence rejected the "
             "matcher's answer.", "",
             f"Not scored: {', '.join(sorted(WORKED_EXAMPLES))}, explained to the labeler as a worked example during "
             f"labeling. Scored: {len(rows)}.", "",
             f"**Suggestions overridden: {len(overrides)} of {len(decided)}** (unsure: {len(rows) - len(decided)}). "
             "Each override is listed under Disagreements.", "",
             "## Agreement by matcher outcome", "",
             "| matcher outcome | stratum | population | sampled | human agrees | agreement (95% CI) |",
             "|---|---|---|---|---|---|"]
    est_missed = 0.0
    for s in sorted({i["stratum"] for i, _ in rows}, key=lambda s: (ORDER.index(s.split(":")[0]), s)):
        sel = [(i, h) for i, h in rows if i["stratum"] == s and h != "unsure"]
        out = s.split(":")[0]
        k = sum(h == out for _, h in sel)
        lo, hi = wilson(k, len(sel))
        agr = f"{k / len(sel):.0%} ({lo:.0%}–{hi:.0%})" if sel else "-"
        lines.append(f"| {out} | {s.split(': ', 1)[1] if ':' in s else ''} | {pop.get(s, 0):,} | {len(sel)} | {k} | {agr} |")
        if out == "not checked" and sel:
            est_missed += pop.get(s, 0) * sum(h in ("matches", "no matching tagged value") for _, h in sel) / len(sel)
    unsure = sum(h == "unsure" for _, h in rows)
    lines += ["", f"Unsure labels, excluded from agreement: {unsure}.", "",
              "## Confusion matrix (rows: matcher, columns: human)", "",
              "| matcher \\ human | " + " | ".join(ORDER + ["unsure"]) + " |", "|---" * 6 + "|"]
    for o in ORDER:
        lines.append(f"| **{o}** | " + " | ".join(str(cm[(o, h)]) for h in ORDER + ["unsure"]) + " |")
    m_sel = [(i, h) for i, h in rows if i["stratum"] == "matches" and h != "unsure"]
    m_prec = sum(h == "matches" for _, h in m_sel) / len(m_sel) if m_sel else float("nan")
    lines += ["", "## Coverage (corpus estimates)", "",
              f"- Claims checked against a tagged value (`matches` + `no matching tagged value`): "
              f"{pop.get('matches', 0) + pop.get('no matching tagged value', 0):,} of {sum(pop.values()):,}.",
              f"- Estimated correct `matches` in the corpus: about {pop.get('matches', 0) * m_prec:,.0f} "
              f"({pop.get('matches', 0):,} × {m_prec:.0%}).",
              f"- Estimated checkable claims the matcher left `not checked` (human said M or N): about "
              f"{est_missed:,.0f}.",
              "- Claims the matcher never extracted (other phrasings, tables) are outside this measurement.", "",
              "## Disagreements", ""]
    for i, h in rows:
        if h != "unsure" and h != i["matcher"]["outcome"]:
            note = labels[i["id"]].get("note")
            lines.append(f"- **{i['id']}** {i['company']} {i['form']} {i['period_end']} · matcher **{i['matcher']['outcome']}**"
                         f"{' (' + i['matcher']['reason'] + ')' if i['matcher']['reason'] else ''} · human **{h}**"
                         f"{' `' + labels[i['id']]['code'] + '`' if labels[i['id']].get('code') else ''}: "
                         f"\"{i['claim']}\"" + (f" (note: {note})" if note else ""))
    (ROOT / "docs" / "claims-eval.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
