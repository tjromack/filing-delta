"""Reproduce every published number from the data release, with no API key (M8, FD-DEC 036).

    python tools/fetch_release.py && python tools/reproduce.py

Checks the release data on disk against release/manifest.json, then rebuilds everything derived (parse, diff, XBRL
facts, claims), re-runs every evaluation and report from recorded model responses, and runs the test suite. It
passes only if no committed file in docs/, tests/ or corpus/ changed: every report regenerated byte for byte.
ANTHROPIC_API_KEY is blanked for every step, so nothing can call a model.
"""
from __future__ import annotations

import json
import os
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
from build_release import MANIFEST, tree_digest  # noqa: E402

PY = sys.executable
STEPS = [
    ("fetch (cache only)", [PY, "-m", "filing_delta.cli", "fetch", "--offline"], {}),
    ("parse sections", [PY, "-m", "filing_delta.cli", "parse"], {}),
    ("diff", [PY, "-m", "filing_delta.cli", "diff"], {}),
    ("XBRL facts", [PY, "-m", "filing_delta.cli", "facts", "--offline"], {}),
    ("MD&A claims", [PY, "-m", "filing_delta.cli", "claims"], {}),
    ("alignment eval", [PY, "tools/eval_alignment.py"], {}),
    ("alignment sweep", [PY, "tools/sweep_alignment.py"], {}),
    ("materiality dev", [PY, "tools/run_materiality.py", "dev", "--offline"], {}),
    ("materiality test", [PY, "tools/run_materiality.py", "test", "--offline"], {}),
    ("materiality test, Haiku", [PY, "tools/run_materiality.py", "test", "--offline"],
     {"ANTHROPIC_MODEL": "claude-haiku-5-5"}),
    ("materiality corpus", [PY, "tools/classify_corpus.py", "report", "--compare", "claude-haiku-5-5"], {}),
    ("materiality re-check", [PY, "tools/score_recheck.py"], {}),
    ("claims eval", [PY, "tools/score_claims.py"], {}),
    ("QA eval", [PY, "tools/run_qa.py", "--offline"], {}),
    ("spancheck", [PY, "tools/spancheck_run.py", "score", "--offline"], {}),
    ("B4 export + validation", [PY, "tools/export_b4.py"], {}),
    ("tests", [PY, "-m", "pytest", "-q"], {}),
]


def main() -> None:
    m = json.loads(MANIFEST.read_text(encoding="utf-8"))
    for rel, want in m["contents"].items():
        got, n = tree_digest(rel)
        if got != want["digest"]:
            raise SystemExit(f"{rel}: doesn't match release {m['tag']} ({n} files vs {want['files']}). "
                             "Run tools/fetch_release.py first.")
    base = {**os.environ, "ANTHROPIC_API_KEY": "", "PYTHONIOENCODING": "utf-8", "PYTHONHASHSEED": "0"}
    base.pop("ANTHROPIC_MODEL", None)
    t0 = time.time()
    for label, cmd, extra in STEPS:
        t = time.time()
        r = subprocess.run(cmd, cwd=ROOT, env={**base, **extra}, capture_output=True, text=True, encoding="utf-8")
        print(f"{'ok ' if r.returncode == 0 else 'FAIL'} {label:26} {time.time() - t:6.1f}s", flush=True)
        if r.returncode:
            print(r.stdout[-3000:], r.stderr[-3000:], sep="\n")
            raise SystemExit(f"step failed: {label}")
    changed = subprocess.run(["git", "status", "--porcelain", "--", "docs", "tests", "corpus", "export"], cwd=ROOT,
                             capture_output=True, text=True).stdout.strip()
    if changed:
        subprocess.run(["git", "--no-pager", "diff", "--stat", "--", "docs", "tests", "corpus", "export"], cwd=ROOT)
        subprocess.run(["git", "--no-pager", "diff", "-U1", "--", "docs", "tests", "corpus", "export"], cwd=ROOT)
        raise SystemExit("REPRODUCTION FAILED: these committed files changed:\n" + changed)
    print(f"\nREPRODUCED: every committed report and golden file regenerated byte for byte "
          f"({time.time() - t0:.0f}s, release {m['tag']}, no API key).")


if __name__ == "__main__":
    main()
