"""Golden section boundaries: proposed by the parser, confirmed by a human (design §2.6).

`propose()` writes tests/golden/sections.json and docs/golden-review.md. The parser never grades itself: an
entry stays `"status": "proposed"` until Trevor reads its boundary context in the review sheet and marks it
`"confirmed"`. A confirmed entry is never overwritten by a re-proposal. If the parser's output for it changes, the
golden test fails, and the change has to be explained.

`rederive()` is the one exception, and a narrow one. A confirmed entry may be refreshed only if its
whitespace-insensitive hash (`words_sha256`) is unchanged: the same words between the same boundaries, with only
paragraph breaks changed. Anything else stays failing until a human looks at it.
"""
from __future__ import annotations

import csv
import hashlib
import json
import re
from pathlib import Path

from ..edgar.cache import ResponseCache
from .blocks import flatten
from .locate import parse_filing, prepare
from .report import SECTION_LABEL

# One filing per archetype x era x mechanism (docs/design/section-parser.md §2.6; corpus/manifest.csv).
GOLDEN_DOCS = {
    "aapl-20250927.htm": "A · iXBRL · linked TOC",
    "a10-k20189292018.htm": "A · pre-iXBRL · split-cell headings",
    "f-20251231.htm": "A · '(Continued)' running headers",
    "tv515153_10k.htm": "A · pre-iXBRL · bare 'ITEM 1A' + title line",
    "d678758d10k.htm": "A · pre-iXBRL · 1,295 '&#146;'-style C1 references",
    "wmt-20250131.htm": "A · straight quotes · January FYE",
    "jpm-20251231.htm": "B · pointer stub · running headers · stated pages",
    "xom-20251231.htm": "B · pointer stub · running headers · no stated pages",
    "ge-20251231.htm": "C · cross-reference index · indented TOC · run-in headings",
    "ge10-k2018.htm": "C · cross-reference index · flat TOC",
    "pfe-12312018x10kshell.htm": "MD&A incorporated from an exhibit (expected failure)",
    "jpm-20260630.htm": "D · 10-Q pointer out · MD&A from TOC anchor only",
    "weys-20260630x10q.htm": "10-Q · no TOC links · Part II Item 1A omitted",
    "brka-20260630.htm": "10-Q · Item 2 heading repeated as running header · pointer out",
}


def _context(doc, idxs, n=2, forward=True):
    out = []
    rng = idxs if forward else reversed(idxs)
    for i in rng:
        if 0 <= i < len(doc.blocks) and i not in doc.furn:
            out.append(doc.blocks[i].text[:200])
            if len(out) == n:
                break
    return out if forward else list(reversed(out))


def propose(root: Path, cache_dir: Path) -> tuple[int, int]:
    cache = ResponseCache(cache_dir)
    manifest = {r["primary_document"]: r for r in csv.DictReader((root / "corpus" / "manifest.csv").open(encoding="utf-8"))}
    path = root / "tests" / "golden" / "sections.json"
    existing = {}
    if path.exists():
        existing = {(e["accession"], e["section"]): e for e in json.loads(path.read_text(encoding="utf-8"))}
    entries, review = [], [
        "# Golden boundary review",
        "",
        "Each section below is the parser's **proposed** boundary. To confirm one, read the context. *Before start* "
        "is the last real text before the section, *first/last chars* are the section's own text, and *after end* "
        "is what follows. Check it against the filing (the link opens it on EDGAR), then set its `status` to "
        "`\"confirmed\"` in `tests/golden/sections.json`. Or say which ones are wrong. Generated by "
        "`filing-delta golden`. The parser never marks its own output as confirmed.",
        "",
    ]
    for doc_name, why in GOLDEN_DOCS.items():
        m = manifest[doc_name]
        raw = cache.get(m["url"]).body
        fl = flatten(raw)
        doc = prepare(fl, m["form"])
        results = parse_filing(fl, m["form"])
        review += [f"## {m['company']} · {m['form']} · period {m['report_date']}", "",
                   f"*Why it's golden:* {why} · [{m['accession']}]({m['url']})", ""]
        for section, r in results.items():
            key = (m["accession"], section)
            prior = existing.get(key)
            entry = {
                "accession": m["accession"], "company": m["company"], "form": m["form"],
                "report_date": m["report_date"], "document": doc_name, "section": section,
                "outcome": r.outcome, "form_kind": r.form_kind, "reasons": r.reasons,
                "chars": len(r.text), "sha256": r.sha256, "words_sha256": words_sha256(r.text),
                "head": r.text[:120], "tail": r.text[-120:],
                "status": "proposed", "note": "",
            }
            if prior and prior.get("status") == "confirmed":
                entry = prior                        # never overwrite a human confirmation
            elif prior and prior.get("note"):
                entry["note"] = prior["note"]
            entries.append(entry)
            review.append(f"### {SECTION_LABEL[section]} — `{r.outcome}` / `{r.form_kind}` · {len(r.text):,} chars · "
                          f"status: **{entry['status']}**")
            review.append("")
            if r.reasons:
                review.append(f"Reasons: `{', '.join(r.reasons)}`")
                review.append("")
            if r.start_block is not None and r.text:
                before = _context(doc, range(r.start_block - 1, max(-1, r.start_block - 40), -1), forward=False)
                after = _context(doc, range(r.end_block or 0, min(len(doc.blocks), (r.end_block or 0) + 40)))
                review += ["| | |", "|---|---|",
                           f"| before start | {' ⏎ '.join(before)} |".replace("\n", " "),
                           f"| heading block | {doc.blocks[r.start_block].text[:200]} |",
                           f"| first chars | {r.text[:300]} |".replace("\n", " ⏎ "),
                           f"| last chars | {r.text[-300:]} |".replace("\n", " ⏎ "),
                           f"| after end | {' ⏎ '.join(after)} |".replace("\n", " "), ""]
            elif r.text:
                review += [f"> {r.text[:400]}", ""]
            else:
                review += ["*(no text: " + ", ".join(r.reasons) + ")*", ""]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(entries, indent=1, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    (root / "docs" / "golden-review.md").write_text("\n".join(review).replace("|", "|") + "\n", encoding="utf-8",
                                                    newline="\n")
    confirmed = sum(e["status"] == "confirmed" for e in entries)
    return len(entries), confirmed


def words_sha256(text: str) -> str:
    """Hash of the text with all whitespace runs collapsed: unchanged by paragraph-break changes, by nothing else."""
    return hashlib.sha256(re.sub(r"\s+", " ", text).strip().encode("utf-8")).hexdigest()


def rederive(root: Path, cache_dir: Path, today: str) -> tuple[list[str], list[str]]:
    """Refresh confirmed entries whose words are unchanged; return (refreshed, still-failing) ids."""
    cache = ResponseCache(cache_dir)
    urls = {r["accession"]: r["url"] for r in csv.DictReader((root / "corpus" / "manifest.csv").open(encoding="utf-8"))}
    path = root / "tests" / "golden" / "sections.json"
    entries = json.loads(path.read_text(encoding="utf-8"))
    parsed: dict[str, dict] = {}
    refreshed, failing = [], []
    for e in entries:
        if e["accession"] not in parsed:
            parsed[e["accession"]] = parse_filing(flatten(cache.get(urls[e["accession"]]).body), e["form"])
        r = parsed[e["accession"]][e["section"]]
        ident = f"{e['document']}:{e['section']}"
        if r.sha256 == e["sha256"] and (r.outcome, r.form_kind) == (e["outcome"], e["form_kind"]):
            continue
        same_words = e.get("words_sha256") == words_sha256(r.text)
        if same_words and (r.outcome, r.form_kind) == (e["outcome"], e["form_kind"]):
            e.update(chars=len(r.text), sha256=r.sha256, head=r.text[:120], tail=r.text[-120:], reasons=r.reasons)
            e["note"] += f" Re-derived {today}: paragraph breaks changed only (words_sha256 unchanged)."
            refreshed.append(ident)
        else:
            failing.append(ident)
    path.write_text(json.dumps(entries, indent=1, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    return refreshed, failing
