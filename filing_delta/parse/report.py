"""Run the parser over the locked corpus; write section texts (data/) and the published report + failure log (docs/).

Deterministic: rows are sorted, no timestamps are written, so a re-run on the same cache produces identical files.
"""
from __future__ import annotations

import csv
import json
from collections import Counter, defaultdict
from dataclasses import dataclass
from pathlib import Path

from ..edgar.cache import ResponseCache
from . import parse_document

SECTION_LABEL = {"10K_1A": "10-K Item 1A", "10K_7": "10-K Item 7", "10Q_P1_2": "10-Q Part I Item 2",
                 "10Q_P2_1A": "10-Q Part II Item 1A"}


@dataclass
class Row:
    cik: int
    company: str
    form: str
    report_date: str
    accession: str
    section: str
    outcome: str
    form_kind: str
    reasons: list[str]
    chars: int
    sha256: str
    evidence: dict


def run(root: Path, cache_dir: Path, out_dir: Path) -> list[Row]:
    cache = ResponseCache(cache_dir)
    manifest = list(csv.DictReader((root / "corpus" / "manifest.csv").open(encoding="utf-8")))
    rows: list[Row] = []
    out_dir.mkdir(parents=True, exist_ok=True)
    with (out_dir / "results.jsonl").open("w", encoding="utf-8", newline="\n") as fh:
        for m in manifest:
            cached = cache.get(m["url"])
            if cached is None:
                raise SystemExit(f"not in cache: {m['url']} (run `filing-delta fetch` first)")
            for section, r in parse_document(cached.body, m["form"]).items():
                ev = {k: v for k, v in r.evidence.items() if k != "block_map"}
                row = Row(int(m["cik"]), m["company"], m["form"], m["report_date"], m["accession"], section,
                          r.outcome, r.form_kind, r.reasons, len(r.text), r.sha256, ev)
                rows.append(row)
                d = out_dir / m["accession"]
                d.mkdir(exist_ok=True)
                (d / f"{section}.txt").write_text(r.text, encoding="utf-8", newline="\n")
                rec = {**row.__dict__, "start_block": r.start_block, "end_block": r.end_block,
                       "block_map": r.evidence.get("block_map", [])}
                fh.write(json.dumps(rec, sort_keys=True, ensure_ascii=False) + "\n")
    rows.sort(key=lambda r: (r.company, r.form, r.report_date, r.section))
    return rows


def _pct(n: int, d: int) -> str:
    return f"{100 * n / d:.1f}%" if d else "—"


def write_reports(rows: list[Row], docs: Path) -> None:
    present = [r for r in rows if r.form_kind != "absent"]
    by_sec: dict[str, Counter] = defaultdict(Counter)
    for r in rows:
        by_sec[r.section][r.outcome if r.form_kind != "absent" else "absent"] += 1
    lines = [
        "# Parse report",
        "",
        "Generated by `filing-delta parse` from the locked corpus (`corpus/manifest.csv`). Regenerating it on the same",
        "cache reproduces this file byte for byte. Outcome model and reasons: `docs/design/section-parser.md` §2.5.",
        "",
        "**Parse-success rate** = `ok` / sections present. *Absent* sections are items a filer verifiably omitted (a",
        "10-Q with no Part II Item 1A; GE's index row marked \"Not applicable\"). They are counted separately and are",
        "neither successes nor failures.",
        "",
        "## By section",
        "",
        "| Section | Present | ok | partial | failed | **success rate** | absent | of which pointer |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for sec in SECTION_LABEL:
        c = by_sec[sec]
        n = c["ok"] + c["partial"] + c["failed"]
        ptr = sum(1 for r in rows if r.section == sec and r.form_kind == "pointer")
        lines.append(f"| {SECTION_LABEL[sec]} | {n} | {c['ok']} | {c['partial']} | {c['failed']} | "
                     f"**{_pct(c['ok'], n)}** | {c['absent']} | {ptr} |")
    tot = Counter(r.outcome for r in present)
    n = len(present)
    lines.append(f"| **All** | {n} | {tot['ok']} | {tot['partial']} | {tot['failed']} | **{_pct(tot['ok'], n)}** | "
                 f"{len(rows) - n} | {sum(1 for r in rows if r.form_kind == 'pointer')} |")

    lines += ["", "## By company", "", "| Company | ok | partial | failed | absent |", "|---|---|---|---|---|"]
    comp: dict[str, Counter] = defaultdict(Counter)
    for r in rows:
        comp[r.company][r.outcome if r.form_kind != "absent" else "absent"] += 1
    for name in sorted(comp):
        c = comp[name]
        lines.append(f"| {name} | {c['ok']} | {c['partial']} | {c['failed']} | {c['absent']} |")

    lines += ["", "## How sections were located", "", "| Mechanism (reason) | Sections |", "|---|---|"]
    mech = Counter(x for r in rows for x in r.reasons)
    for k, v in sorted(mech.items(), key=lambda kv: (-kv[1], kv[0])):
        lines.append(f"| `{k}` | {v} |")
    no_reason = sum(1 for r in rows if not r.reasons)
    lines.append(f"| *(no reason: heading and TOC anchor agree)* | {no_reason} |")

    full10k = sorted(r.chars for r in present if r.form == "10-K" and r.form_kind == "full" and r.outcome != "failed")
    if full10k:
        q = lambda p: full10k[min(len(full10k) - 1, int(p * len(full10k)))]  # noqa: E731
        lines += ["", "## Length floor calibration (10-K, full sections)", "",
                  f"The `too_short` gate fires below 5,000 characters for a full 10-K Item 1A or Item 7. Over the "
                  f"{len(full10k)} parsed full 10-K sections: min {full10k[0]:,} · p05 {q(0.05):,} · median "
                  f"{q(0.5):,} · max {full10k[-1]:,} characters. The floor sits well below the smallest real section,"
                  " so it only catches stubs that were not recognized as pointers."]
    (docs / "parse-report.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")

    fl = ["# Parse failures and partials", "",
          "Every section that did not come out `ok`, with its reasons and evidence (pin 4: nothing is skipped",
          "silently). Generated by `filing-delta parse`.", "",
          "| Company | Form | Period | Accession | Section | Outcome | Reasons | Evidence |", "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        if r.outcome == "ok":
            continue
        ev = {k: r.evidence[k] for k in ("stated_pages", "observed_pages", "pointer_stub", "xref_row",
                                         "heading_candidates", "anchor_targets", "inner_headings") if k in r.evidence}
        evs = "; ".join(f"{k}={json.dumps(v, ensure_ascii=False)[:160]}" for k, v in ev.items()).replace("|", "\\|")
        fl.append(f"| {r.company} | {r.form} | {r.report_date} | {r.accession} | {SECTION_LABEL[r.section]} | "
                  f"{r.outcome} | {', '.join(r.reasons)} | {evs} |")
    (docs / "parse-failures.md").write_text("\n".join(fl) + "\n", encoding="utf-8", newline="\n")
