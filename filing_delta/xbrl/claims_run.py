"""`filing-delta claims`: run the headline-claim matcher over every MD&A section (FD-DEC 025 option B).

Reads data/sections/ and data/facts/ (run `parse` and `facts` first). Writes data/claims/<accession>.json and
docs/claims-report.md: outcome counts, the reasons claims went unchecked, and coverage per company and metric.
"""
from __future__ import annotations

import hashlib
import json
from collections import Counter
from pathlib import Path

from .claims import find_claims, fiscal_year
from .facts import Fact

SECTION = {"10-K": "10K_7", "10-Q": "10Q_P1_2"}
OUTCOMES = ("matches", "no matching tagged value", "non-GAAP wording", "not checked")


def matcher_version() -> str:
    """A hash of the matcher's source: the rules are frozen before any sample is labeled, like the M4 prompt."""
    src = (Path(__file__).with_name("claims.py").read_bytes() + Path(__file__).with_name("periods.py").read_bytes())
    return hashlib.sha256(src.replace(b"\r\n", b"\n")).hexdigest()[:12]


def run(sections_dir: Path, facts_dir: Path, out_dir: Path, docs_dir: Path) -> list[dict]:
    out_dir.mkdir(parents=True, exist_ok=True)
    recs = []
    for p in sorted(facts_dir.glob("*.json")):
        fr = json.loads(p.read_text(encoding="utf-8"))
        sec = sections_dir / fr["accession"] / f"{SECTION[fr['form']]}.txt"
        rec = {k: fr[k] for k in ("accession", "company", "form", "report_date", "period_end")}
        rec["section"] = SECTION[fr["form"]]
        if not sec.exists():
            rec.update(claims=[], status="no MD&A section text (see docs/parse-report.md)")
        else:
            text = sec.read_text(encoding="utf-8")
            dei = fr.get("dei") or {}
            fy = fiscal_year(fr["period_end"], fr["form"], (dei.get("CurrentFiscalYearEndDate") or {}).get("text"))
            rec["dei_fiscal_year"] = (dei.get("DocumentFiscalYearFocus") or {}).get("text")
            fp = (dei.get("DocumentFiscalPeriodFocus") or {}).get("text")
            facts = [Fact.from_json(f) for f in fr["facts"]]
            claims = find_claims(text, facts, fr["period_end"], fr["form"], fy, fp)
            assert all(text[c.start:c.end] == c.text for c in claims)      # every span is exact
            rec.update(claims=[c.to_json() for c in claims], status="ok", fiscal_year=fy, fiscal_period=fp)
        (out_dir / f"{fr['accession']}.json").write_text(json.dumps(rec, ensure_ascii=False, sort_keys=True) + "\n",
                                                         encoding="utf-8", newline="\n")
        recs.append(rec)
    write_report(recs, docs_dir)
    return recs


def write_report(recs: list[dict], docs_dir: Path) -> None:
    claims = [(r, c) for r in recs for c in r["claims"]]
    oc = Counter(c["outcome"] for _, c in claims)
    reasons = Counter(c["reason"].split(" (")[0] for _, c in claims if c["outcome"] == "not checked")
    n = len(claims)
    lines = ["# MD&A headline claims vs. tagged values", "",
             f"Matcher version `{matcher_version()}` (FD-DEC 025 option B, no model). Item 7 of {sum(r['form'] == '10-K' for r in recs)} "
             f"10-Ks and Part I Item 2 of {sum(r['form'] == '10-Q' for r in recs)} 10-Qs (the locked corpus), "
             "compared with the same filing's consolidated, current-period XBRL values. Generated by "
             "`filing-delta claims`.", "",
             "MD&A is unaudited management discussion. `no matching tagged value` means the stated amount was not "
             "found among the tagged values at its stated precision; it does not mean the statement is wrong, since "
             "MD&A may define a metric differently from the tag. Precision of each outcome against hand labels: "
             "`docs/claims-eval.md`.", "",
             f"Claims found: **{n:,}**.", "", "| outcome | claims | share |", "|---|---|---|"]
    for o in OUTCOMES:
        lines.append(f"| {o} | {oc[o]:,} | {oc[o] / n:.0%} |" if n else f"| {o} | 0 | - |")
    lines += ["", "Why claims were not checked:", ""] + [f"- {k}: {v:,}" for k, v in reasons.most_common()]
    lines += ["", "| company | claims | matches | no matching tagged value | non-GAAP wording | not checked |",
              "|---|---|---|---|---|---|"]
    for co in sorted({r["company"] for r in recs}):
        cc = Counter(c["outcome"] for r, c in claims if r["company"] == co)
        lines.append(f"| {co} | {sum(cc.values())} | " + " | ".join(str(cc[o]) for o in OUTCOMES) + " |")
    lines += ["", "| metric | claims | matches | no matching tagged value | non-GAAP wording | not checked |",
              "|---|---|---|---|---|---|"]
    for m in sorted({c["metric"] for _, c in claims}):
        cc = Counter(c["outcome"] for _, c in claims if c["metric"] == m)
        lines.append(f"| {m} | {sum(cc.values())} | " + " | ".join(str(cc[o]) for o in OUTCOMES) + " |")
    off = [r for r in recs if r.get("dei_fiscal_year") and r["dei_fiscal_year"] != r.get("fiscal_year")]
    lines += ["", f"Fiscal year is derived from the period end and fiscal-year-end date. Filings whose cover tag "
              f"`dei:DocumentFiscalYearFocus` disagrees: {len(off)}"
              + (" (" + ", ".join(f"{r['company']} {r['form']} {r['report_date']}: tagged {r['dei_fiscal_year']}, "
                                  f"derived {r['fiscal_year']}" for r in off) + ")" if off else "") + "."]
    missing = [r for r in recs if r["status"] != "ok"]
    if missing:
        lines += ["", f"Filings with no MD&A text: {len(missing)} ("
                  + ", ".join(f"{r['company']} {r['form']} {r['report_date']}" for r in missing) + ")."]
    (docs_dir / "claims-report.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
